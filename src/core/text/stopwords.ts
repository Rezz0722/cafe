/**
 * واژه‌های بی‌محتوا در جست‌وجو.
 *
 * بدون این، باقی‌مانده‌ی یک جمله‌ی طبیعی («کافه‌ای آروم برای کار در سجاد»
 * بعد از استخراج نیت‌ها می‌شود «کافه ای برای در») به‌عنوان فیلتر روی نام
 * اعمال می‌شود و همه‌چیز را حذف می‌کند.
 */

const STOPWORDS = new Set([
  // حروف اضافه و ربط
  'با', 'برای', 'در', 'از', 'به', 'که', 'را', 'و', 'یا', 'تا', 'بر',
  'روی', 'زیر', 'کنار', 'نزدیک', 'اطراف', 'حوالی', 'سمت', 'طرف',
  'توی', 'تو', 'داخل', 'بیرون', 'باز', 'بسته',
  // اشاره و ضمیر
  'این', 'اون', 'آن', 'همین', 'همان', 'یک', 'ی', 'ای', 'هم', 'خیلی',
  'من', 'ما', 'شما', 'خودم', 'خودمون',
  // افعال و عبارت‌های پرتکرار جست‌وجو
  'میخوام', 'می خوام', 'میخام', 'دنبال', 'میگردم', 'می گردم', 'باشه',
  'هست', 'باشد', 'داره', 'دارد', 'بده', 'پیدا', 'کن', 'کنم', 'بریم',
  'جایی', 'جای', 'جا', 'مکان', 'بهترین', 'خوب', 'عالی', 'چه', 'کجا',
  // نوع مکان — قبلاً با فیلتر kind پوشش داده می‌شود
  'کافه', 'کافی', 'شاپ', 'رستوران', 'قهوه',
])

/** واژه‌های بی‌محتوا را از یک رشته‌ی *نرمال‌شده* حذف می‌کند. */
export function stripStopwords(normalized: string): string {
  if (!normalized) return ''
  return normalized
    .split(' ')
    .filter((word) => word && !STOPWORDS.has(word))
    .join(' ')
    .trim()
}

export function isStopword(word: string): boolean {
  return STOPWORDS.has(word)
}
