/**
 * پیش‌پردازش کوئری جست‌وجو — تشخیص منطقه و حذف کلمات توقف.
 *
 * ═══ باگی که این ماژول می‌بندد ═══
 *
 * جست‌وجو مستقیم به `MATCH(name, name_normalized) AGAINST (…)` می‌رفت، در حالت
 * NATURAL LANGUAGE. برای «کافه‌ای در احمد آباد» نتیجه این بود:
 *
 *   • «کافه» در نام **اکثر** ۳۳۱ مجموعه هست، پس تقریباً همه امتیاز می‌گرفتند.
 *   • «احمد آباد» با نیم‌فاصله‌ی متفاوت به نام منطقه وصل نمی‌شد.
 *   • منطقه هیچ‌وقت به شرط `WHERE district_id = …` تبدیل نمی‌شد، پس کافه‌های
 *     وکیل‌آباد و کوثر بالاتر از کافه‌های خودِ احمدآباد می‌آمدند.
 *
 * پس کوئری قبل از رسیدن به دیتابیس از اینجا رد می‌شود: نام منطقه بیرون کشیده
 * و به یک شرط **سخت‌گیرانه** تبدیل می‌شود، و باقی‌مانده‌ی متن از کلمات توقف
 * پاک می‌شود.
 *
 * ═══ چرا پنجره‌ی واژه و نه substring ═══
 *
 * وسوسه‌ی ساده این است: `squashFa(query).includes(squashFa(districtName))`.
 * ولی آن مرزِ واژه ندارد و «ارگ» را وسط واژه‌های دیگر هم پیدا می‌کند. اینجا
 * کوئری به واژه شکسته می‌شود و **پنجره‌های واژه‌ی پشت‌سرهم** با نام منطقه
 * مقایسه می‌شوند — پس «احمد» + «آباد» به «احمدآباد» می‌رسد ولی هیچ واژه‌ای
 * از وسط شکسته نمی‌شود.
 *
 * پنجره‌ی بلندتر برنده است: «میدان آزادی» باید کل نام منطقه باشد، نه اینکه
 * «میدان» دور ریخته شود و «آزادی» تنها بماند.
 *
 * ═══ ابهامی که اینجا حل نمی‌شود ═══
 *
 * کافه‌ای که *نامش* «سجاد» است با *منطقه‌ی* سجاد قابل تفکیک نیست. این ماژول
 * منطقه را ترجیح می‌دهد (همان چیزی که کاربر تقریباً همیشه منظورش است) ولی
 * `matchedDistrict` را برمی‌گرداند تا UI بتواند بگوید «منطقه‌ی سجاد تشخیص داده
 * شد» و راه برگشت به جست‌وجوی متنی را نشان دهد. تشخیصِ خاموش، بدترین حالت
 * است: کاربر نمی‌فهمد چرا نتیجه‌اش عوض شد.
 */

import { normalizeFa, squashFa } from '@/core/text/normalize'

/**
 * کلمات توقف.
 *
 * ═══ چرا این فهرست محافظه‌کارانه است ═══
 *
 * هر واژه‌ای که اینجا بیاید، دیگر هرگز به‌عنوان *نام کافه* جست‌وجو نمی‌شود.
 * «دنج» و «باحال» عمداً نیامده‌اند: ممکن است نام واقعی یک کافه باشند و
 * حذفشان یعنی آن کافه هیچ‌وقت پیدا نمی‌شود. فقط واژه‌هایی اینجاست که در نام
 * کسب‌وکار بی‌معنی‌اند.
 */
