/**
 * نام‌های دیگری که مردم برای همان منطقه به کار می‌برند.
 *
 * کلید، `slug` منطقه است — نه نامش — تا اگر نام نمایشی در پنل ادمین عوض شد،
 * این نگاشت نشکند.
 */
const DISTRICT_ALIASES: Record<string, string[]> = {
  sajad: ['بلوار سجاد', 'سجادیه'],
  vakilabad: ['وکیل آباد', 'وکیلآباد'],
  ahmadabad: ['احمد آباد'],
  ghasemabad: ['قاسم آباد'],
  malekabad: ['ملک آباد'],
  kuhsangi: ['کوه سنگی'],
  'emam-reza': ['امام رضا', 'بست امام رضا'],
  'haft-tir': ['هفت تیر', '۷ تیر', '7 تیر'],
  'rah-ahan': ['راه آهن'],
  torghabeh: ['طرقبه شاندیز'],
  haram: ['حرم', 'حرم مطهر', 'اطراف حرم'],
  azadi: ['میدان آزادی', 'آزادی'],
  'faramarz-abbasi': ['فرامرز عباسی', 'فرامرز'],
  hashemieh: ['هاشمیه'],
}

/** حداکثر تعداد واژه‌ای که یک نام منطقه می‌تواند داشته باشد. */
const MAX_DISTRICT_WORDS = 4

export interface DistrictOption {
  id: string
  slug: string
  name: string
}

export interface ParsedQuery {
  /**
   * منطقه‌ی تشخیص‌داده‌شده — به شرطِ سخت‌گیرانه‌ی `WHERE district_id` تبدیل
   * می‌شود. `null` یعنی کاربر منطقه‌ای نگفته.
   */
  districtId: string | null
  /** نام و slugِ منطقه‌ی تشخیص‌داده‌شده — برای پیام «منطقه‌ی … تشخیص داده شد». */
  district: DistrictOption | null
  /**
   * متنِ باقی‌مانده برای جست‌وجوی نام کافه. رشته‌ی خالی یعنی «فیلتری روی نام
   * نیست» — نه «هیچ نتیجه‌ای نباید بیاید».
   */
  text: string
  /** آیا چیزی از کوئری اصلی حذف شد؟ برای اینکه UI بتواند شفاف باشد. */
  changed: boolean
}

/** واژه‌های یک نام منطقه، نرمال‌شده. */
function districtWordForms(district: DistrictOption): string[][] {
  const names = [district.name, ...(DISTRICT_ALIASES[district.slug] ?? [])]
  return names.map((name) => normalizeFa(name).split(' ').filter(Boolean))
}

/**
 * تشخیص منطقه و پاک‌سازی کوئری.
 *
 * `districts` تزریق می‌شود نه اینکه از دیتابیس خوانده شود: این ماژول خالص
 * می‌ماند و مستقیم قابل تست است — بدون آن، تستِ «احمد آباد به احمدآباد وصل
 * می‌شود» به یک دیتابیس زنده نیاز داشت.
 */
export function parseSearchQuery(raw: string, districts: DistrictOption[]): ParsedQuery {
  const normalized = normalizeFa(raw ?? '')
  if (!normalized) {
    return { districtId: null, district: null, text: '', changed: false }
  }

  const words = normalized.split(' ').filter(Boolean)

  /*
    همه‌ی شکل‌های ممکنِ نام منطقه، به‌صورت «امضای فشرده → منطقه».

    فشرده‌سازی (`squashFa`) فاصله و نیم‌فاصله را کاملاً برمی‌دارد، پس
    «احمد آباد» و «احمدآباد» و «احمد‌آباد» یک امضا می‌گیرند — همان یکسان‌سازی
    املایی که لازم است.
  */
  const signatures = new Map<string, { district: DistrictOption; wordCount: number }>()
  for (const district of districts) {
    for (const form of districtWordForms(district)) {
      if (form.length === 0) continue
      const key = squashFa(form.join(' '))
      // امضای کوتاه‌تر از سه نویسه ریسکِ تطابق تصادفی دارد.
      if (key.length < 3) continue
      const existing = signatures.get(key)
      // اگر دو منطقه یک امضا داشتند، اولی (ترتیب پنل ادمین) برنده است.
      if (!existing) signatures.set(key, { district, wordCount: form.length })
    }
  }

  /*
    پنجره‌ی بلندتر اول امتحان می‌شود تا «میدان آزادی» قبل از «آزادی» گرفته
    شود. در هر طول، از چپ به راست — اولین تطابق برنده است.
  */
  let matched: { district: DistrictOption; start: number; length: number } | null = null
  for (let size = Math.min(MAX_DISTRICT_WORDS, words.length); size >= 1 && !matched; size--) {
    for (let start = 0; start + size <= words.length; start++) {
      const key = squashFa(words.slice(start, start + size).join(' '))
      const hit = signatures.get(key)
      if (hit) {
        matched = { district: hit.district, start, length: size }
        break
      }
    }
  }

  const rest = matched
    ? [...words.slice(0, matched.start), ...words.slice(matched.start + matched.length)]
    : [...words]

  /*
    حذف کلمات توقف و واژه‌های ژنریکِ نشانی از باقی‌مانده.

    مقایسه روی شکل فشرده انجام می‌شود تا «کافه‌ای» و «کافهای» هر دو بروند.
  */
  const kept = rest.filter((word) => {
    const squashed = squashFa(word)
    if (!squashed) return false
    if (STOP_WORDS.has(squashed)) return false
    if (ADDRESS_WORDS.has(squashed)) return false
    return true
  })

  /*
    یک‌نویسه‌ای‌ها هم می‌روند: `MATCH … AGAINST` روی «ی» یا «ا» چیزی پیدا
    نمی‌کند و فقط نتیجه را صفر می‌کند.
  */
  const text = kept.filter((word) => word.length > 1).join(' ')

  return {
    districtId: matched?.district.id ?? null,
    district: matched?.district ?? null,
    text,
    changed: text !== normalized,
  }
}
